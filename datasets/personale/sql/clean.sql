SELECT
    CAST("ANNO" AS INTEGER) AS anno,
    CAST("GENERE" AS VARCHAR) AS genere,
    CAST("COD_QUALIFICA" AS VARCHAR) AS codice_qualifica,
    CAST("DESC_QUALIFICA" AS VARCHAR) AS desc_qualifica,
    TRY_CAST("N_PERS_DR" AS INTEGER) AS numero
FROM raw_input
WHERE
    TRY_CAST("ANNO" AS INTEGER) IS NOT NULL
    AND TRY_CAST("N_PERS_DR" AS INTEGER) IS NOT NULL
