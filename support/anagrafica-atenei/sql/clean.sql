    CAST(r."NomeEsteso" AS VARCHAR) AS nome_esteso,
    CAST(r."NomeOperativo" AS VARCHAR) AS nome_operativo,
    CAST(r."Status" AS VARCHAR) AS status,
    CAST(r."Descrizione" AS VARCHAR) AS descrizione,
    CAST(r."StataleLibera" AS VARCHAR) AS tipo,
    CAST(r."CITTA" AS VARCHAR) AS citta,
    CAST(r."PROVINCIA" AS VARCHAR) AS provincia,
    p.sigla_provincia,
    p.cod_provincia_istat,
    CAST(r."REGIONE" AS VARCHAR) AS regione,
    CAST(r."NOME_REGIONE_MACRO" AS VARCHAR) AS macro_area
FROM raw_input r
LEFT JOIN province_istat p
    ON UPPER(TRIM(CAST(r."PROVINCIA" AS VARCHAR))) = p.provincia
